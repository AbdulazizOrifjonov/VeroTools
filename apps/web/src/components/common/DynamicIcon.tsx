function normalise(name: string): string {
  // accept "shield-check" / "shield_check" / "ShieldCheck"
  if (/[-_\s]/.test(name) || /^[a-z]/.test(name)) {
    return name
      .split(/[-_\s]+/)
      .filter(Boolean)
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('');
  }
  return name;
}

export function iconByName(name: string | undefined | null, fallback: LucideIcon = Wrench): LucideIcon {
  if (!name) return fallback;
  return ICONS[name] ?? ICONS[normalise(name)] ?? fallback;
}

export function DynamicIcon({ name, fallback, ...props }: LucideProps & { name?: string | null; fallback?: LucideIcon }) {
  const Icon = iconByName(name, fallback);
  return <Icon aria-hidden="true" {...props} />;
}
